function mdxString(value) {
  return JSON.stringify(String(value ?? ''));
}

// API text lands in MDX and must stay inert text there. Escaped: expressions
// and JSX ({ } < >), links and images ([ ], so no javascript: URLs or remote
// pixels), emphasis, code and table syntax, and block markers at a line's
// start (headings, setext underlines, lists). A line starting with `import`
// or `export` would compile to ESM, so its first letter becomes a character
// reference. (JSX string expressions would be simpler, but Mintlify leaves
// them out of the server-rendered HTML.)
function mdxText(value) {
  return String(value || '')
    .replace(/\\/g, '\\\\')
    .replace(/[{}[\]|*_`~#]/g, ch => `\\${ch}`)
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/^([ \t]*)([-+=])/gm, '$1\\$2')
    .replace(/^([ \t]*)(import|export)\b/gm, (match, space, word) => `${space}&#${word.charCodeAt(0)};${word.slice(1)}`);
}

