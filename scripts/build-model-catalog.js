// "ByteDance Seed" + "Seed Audio 1.0" reads "ByteDance Seed Audio 1.0": words
// the name already starts with aren't repeated, and a name that starts with
// the maker ("Kling 3" by Kling AI) stands alone.
function withProvider(provider, name) {
  const words = provider.split(/\s+/);
  const lower = name.toLowerCase();
  if (lower.startsWith(`${words[0].toLowerCase()} `)) return name;
  for (let i = 1; i < words.length; i++) {
    const tail = words.slice(i).join(' ').toLowerCase();
    if (lower === tail || lower.startsWith(`${tail} `)) return [...words.slice(0, i), name].join(' ');
  }
  return `${provider} ${name}`;
}

// One value for the family, or each variant's when they differ.
function perVariant(variants, valueOf) {
  const values = variants.map(v => valueOf(v));
  if (uniq(values).length < 2) return values[0] || null;
  return variants.map((v, i) => (values[i] ? `${variantLabel(v)}: ${values[i]}` : null)).filter(Boolean).join('; ');
}

// The page's server-rendered text: what crawlers and readers without
// JavaScript get, and what "Plain-text specification" shows.
function specMarkdown(family, variants, providers, related, familiesBySlug, modelsById, samples) {
  const f = familyFacts(family, variants, providers);
  const primary = f.primary;
  const name = mdxText(family.name);
  // The hub renders the page's H1, so the static text starts at H2.
  const lines = [`## ${name} API`, ''];
  const kind = family.modality === 'video' ? listPhrase(f.modes) || 'video' : listPhrase(f.tasks.map(t => TASK_PHRASES[t]).filter(Boolean)) || family.modality;
  const article = /^[aeiou]/i.test(kind) ? 'an' : 'a';
  lines.push(`${name} is ${article} ${mdxText(kind)} model${f.provider ? ` by ${mdxText(f.provider)}` : ''}, available on the Venice API as \`${primary.id}\`. ${privacySentence(family.privacy || [primary.privacy])}`);
  if (family.description) lines.push('', mdxText(family.description));

  lines.push('', `### ${name} API pricing`, '', '| Model ID | Variant | Privacy | Price |', '|---|---|---|---|');
  for (const v of variants) {
    lines.push(`| \`${v.id}\` | ${variantLabel(v)} | ${privacyLabel(v.privacy)} | ${mdxText(priceLabel(v))} |`);
  }
  const quotes = primary.pricing?.quotes;
  if (family.modality === 'video' && quotes && primary.video?.resolutions?.length && primary.video?.durations?.length) {
    const res = primary.video.resolutions.filter(r => r.height).sort((a, b) => a.height - b.height);
    const audio = primary.video.audio === 'native' ? 'on' : 'off';
    const table = hub().helpers.clipTable(primary, res, audio) || { rows: primary.video.durations, rates: null, note: null };
    lines.push('', `Clip prices for \`${primary.id}\`${audio === 'on' ? ' with audio' : ', silent'}:`, '', `| Duration | ${res.map(r => r.label).join(' | ')} |`, `|---|${res.map(() => '---').join('|')}|`);
    if (table.rates) lines.push(`| Per second | ${table.rates.map(money).join(' | ')} |`);
    for (const d of table.rows) {
      lines.push(`| ${d.seconds ? `${d.seconds}s` : d.value} | ${res.map(r => money(quotes[`${r.value}|${d.value}|${audio}`]) || '—').join(' | ')} |`);
    }
    if (table.note) lines.push('', table.note);
  }

  const tierLabels = uniq(variants.map(v => privacyLabel(v.privacy))).join(', ');
  const { statusText } = hub().helpers;
  const specs = [['Provider', f.provider], ['Released', primary.created ? hub().helpers.fmtDate(primary.created) : null], ['Privacy', tierLabels],
    ['Status', perVariant(variants, statusText)],
    ['Open weights', family.openWeights ? 'Yes' : null], ['License', primary.license]];
  if (primary.text) {
    const t = primary.text;
    specs.push(['Context window', t.context ? `${fmtTokens(t.context)} tokens` : null], ['Max output', t.maxOutput ? `${fmtTokens(t.maxOutput)} tokens` : null],
      ['Reasoning effort', t.reasoning?.effort?.length ? t.reasoning.effort.join(', ') : t.reasoning ? 'Not adjustable' : null],
      ['Served precision', t.quantization ? t.quantization.toUpperCase() : null]);
  }
  if (primary.video) {
    const v = primary.video;
    specs.push(['Modes', listPhrase(f.modes)], ['Resolutions', v.resolutions?.map(r => r.label).join(', ')], ['Durations', v.durations ? hub().helpers.durationText(v.durations) : undefined],
      ['Aspect ratios', v.aspectRatios?.join(', ')], ['Audio', v.audio === 'native' ? 'Always generated' : v.audio === 'optional' ? 'Optional' : 'None']);
  }
  if (primary.image) {
    const i = primary.image;
    specs.push(['Resolutions', i.resolutions?.join(', ')], ['Aspect ratios', i.aspectRatios?.filter(a => a !== 'auto').join(', ')], ['Prompt limit', i.promptLimit ? `${i.promptLimit.toLocaleString('en-US')} characters` : null]);
  }
  if (primary.task === 'tts') specs.push(['Voices', primary.audio?.voices?.length || null], ['Formats', primary.audio?.formats?.join(', ')]);
  if (primary.embedding) specs.push(['Dimensions', primary.embedding.dimensions?.toLocaleString('en-US')], ['Max input', primary.embedding.maxInputTokens ? `${fmtTokens(primary.embedding.maxInputTokens)} tokens` : null]);
  const specRows = specs.filter(([, value]) => value != null && value !== '');
  if (specRows.length) {
    lines.push('', `### ${name} specifications`, '', '| Spec | Value |', '|---|---|', ...specRows.map(([label, value]) => `| ${label} | ${mdxText(value)} |`));
  }

  const recommended = (primary.endpoints || []).find(e => e.recommended) || (primary.endpoints || [])[0];
  if (samples && samples.curl) {
    lines.push('', `### How to use the ${name} API`, '');
    if (recommended) lines.push(`Send requests to \`${recommended.method} https://api.venice.ai/api/v1${recommended.path}\` with \`"model": "${primary.id}"\` and your API key.`, '');
    lines.push('```bash', samples.curl, '```');
  }

  const links = [...(related.versions || []), ...(related.similar || [])]
    .filter((slug, i, all) => all.indexOf(slug) === i && familiesBySlug[slug])
    .map(slug => {
      const other = familiesBySlug[slug];
      const price = priceLabel(modelsById[other.primary]);
      return `- [${mdxText(other.name)} API](/models/${slug}): ${mdxText(price)}`;
    });
  if (links.length) lines.push('', '### Related models', '', ...links);
  return lines.join('\n');
}

// Reuses the request builders from the compiled hub bundle, so the page's
// static text shows the same example as the interactive API section.
function codeSamplesFor(model) {
  const endpoint = (model.endpoints || []).find(e => e.recommended);
  return hub().codeSamples(model, endpoint && endpoint.id);
}

function priceLabel(model) {
  return hub().helpers.priceSummary(model) || (model.modality === 'audio' ? 'Use /audio/quote' : '—');
}

// The prices a model page's pricing comparison lines up: input and output for
// text, each resolution plus the family's edit price for image.
function comparablePricing(family, modelsById) {
  const primary = modelsById[family.primary];
  const p = primary.pricing || {};
  if (primary.task === 'chat') return { input: p.input, output: p.output };
  if (primary.modality !== 'image') return null;
  const editor = family.variants.map(id => modelsById[id]).find(m => m.task === 'image-edit');
  const edit = editor?.pricing ? (editor.pricing.edit ?? editor.pricing.perImage) : null;
  return { byResolution: p.byResolution, perImage: p.perImage, edit };
}

function relatedSummary(slugs, familiesBySlug, modelsById) {
  return slugs.map(slug => {
    const family = familiesBySlug[slug];
    const primary = modelsById[family.primary];
    return compact({
      slug,
      name: family.name,
      provider: family.provider,
      modality: family.modality,
      privacy: family.privacy,
      created: family.created,
      headline: primary.headline,
      pricing: comparablePricing(family, modelsById),
      videoFrom: primary.pricing?.fromPerSecond ?? null,
      variants: family.variants.length
    });
  });
}

function renderPage(family, variants, related, providers, familiesBySlug, modelsById) {
  const primary = variants.find(v => v.id === family.primary) || variants[0];
  const pageData = {
    family: compactFamily(family),
    models: variants.map(stripForPage),
    related: {
      similar: relatedSummary(related.similar, familiesBySlug, modelsById),
      versions: relatedSummary(related.versions, familiesBySlug, modelsById)
    },
    providers: Object.fromEntries([...new Set([family.provider, ...related.similar.concat(related.versions).map(s => familiesBySlug[s].provider)])]
      .filter(slug => providers[slug]).map(slug => [slug, providers[slug]]))
  };
  return [
    '---',
    GENERATED_MARKER,
    `title: ${mdxString(seoTitle(family))}`,
    // Mintlify's breadcrumb shows the sidebar title: the model, not "<model> API".
    `sidebarTitle: ${mdxString(family.name)}`,
    `description: ${mdxString(seoDescription(family, variants, providers))}`,
    `"og:title": ${mdxString(seoHeadTitle(family, variants))}`,
    `keywords: ${JSON.stringify(seoKeywords(family, variants, providers))}`,
    'mode: "custom"',
    '---',
    '',
    'import { HubMount } from "/snippets/model-hub-mount.jsx"',
    '',
    `<HubMount view="ModelPage" data={${JSON.stringify(pageData)}} />`,
    '',
    // Outside <HubMount>: Mintlify server-renders page MDX, but not snippet
    // component children, raw <details> or <noscript>. This is the text
    // crawlers without JavaScript read; <Accordion> keeps it collapsed.
    '<div className="vx-static">',
    '',
    '<Accordion title="Plain-text specification">',
    '',
    specMarkdown(family, variants, providers, related, familiesBySlug, modelsById, codeSamplesFor(primary)),
    '',
    '</Accordion>',
    '',
    '</div>',
    ''
  ].join('\n');
}

function stripForPage(model) {
  const { familyKey, familyName, ...rest } = model;
  return compact(rest);
}

function writePages(families, modelsById, providers, relatedBySlug) {
  const expected = new Set();
  const familiesBySlug = Object.fromEntries(families.map(f => [f.slug, f]));
  for (const family of families.filter(f => !PAGE_FILTER || PAGE_FILTER.has(f.slug))) {
    const file = path.join(MODELS_DIR, `${family.slug}.mdx`);
    expected.add(file);
    const variants = family.variants.map(id => modelsById[id]);
    const related = relatedBySlug[family.slug];
    const contents = renderPage(family, variants, related, providers, familiesBySlug, modelsById);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf-8') : null;
    if (current !== null && !isGenerated(current)) {
      throw new Error(`Refusing to overwrite hand-authored page models/${family.slug}.mdx`);
    }
    if (current !== contents) fs.writeFileSync(file, contents, 'utf-8');
  }
  // Remove pages for families that no longer exist. A --pages preview
  // renders a subset, so it leaves the other pages alone.
  const removed = [];
  if (PAGE_FILTER) return removed;
  for (const name of fs.readdirSync(MODELS_DIR)) {
    const file = path.join(MODELS_DIR, name);
    if (!name.endsWith('.mdx') || expected.has(file)) continue;
    if (isGenerated(fs.readFileSync(file, 'utf-8'))) {
      const slug = name.replace(/\.mdx$/, '');
      removed.push({ slug, data: readPageData(slug) });
      fs.unlinkSync(file);
    }
  }
  return removed;
}

// Where a removed family's URL goes: the family that replaces it, when its
// deprecation names a model that still has a page, else its modality's
// catalog page.
const CATALOG_PAGES = {
  text: '/models/text', image: '/models/image', video: '/models/video', embedding: '/models/embeddings',
  tts: '/models/text-to-speech', stt: '/models/speech-to-text', music: '/models/music', sfx: '/models/music'
};

function redirectFor({ slug, data }, families) {
  const family = data?.family || {};
  const replacements = (data?.models || []).map(m => m.deprecation?.replacement).filter(Boolean);
  const successor = families.find(f => replacements.some(id => f.variants.includes(id)));
  const destination = successor ? `/models/${successor.slug}`
    : CATALOG_PAGES[family.modality === 'audio' ? family.task : family.modality] || '/models/overview';
  return { source: `/models/${slug}`, destination };
}

// Indexed links to removed pages keep working. A redirect never shadows a
// live page, so one is dropped when its slug gets a page again.
function updateRedirects(docs, families, removed) {
  const live = new Set(families.map(f => `/models/${f.slug}`));
  const added = removed.map(page => redirectFor(page, families));
  const sources = new Set(added.map(r => r.source));
  docs.redirects = [...(docs.redirects || []).filter(r => !live.has(r.source) && !sources.has(r.source)), ...added];
}

function updateDocsNavigation(families, removed) {
  const file = path.join(ROOT, 'docs.json');
  const raw = fs.readFileSync(file, 'utf-8');
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const docs = JSON.parse(raw);
  const english = docs.navigation.languages.find(language => language.language === 'en');
  const tab = english?.tabs.find(t => t.tab === 'Models');
  if (!tab) throw new Error('docs.json has no English "Models" tab');
  let group = tab.groups.find(g => g.group === NAV_GROUP) || tab.groups.find(g => g.hidden && g.searchable);
  if (!group) {
    group = { group: NAV_GROUP, hidden: true, searchable: true, pages: [] };
    tab.groups.push(group);
  }
  group.group = NAV_GROUP;
  group.hidden = true;
  group.searchable = true;
  group.pages = families.map(f => `models/${f.slug}`).sort();
  updateRedirects(docs, families, removed);
  const out = JSON.stringify(docs, null, 2).replace(/\n/g, eol) + eol;
  if (out !== raw) fs.writeFileSync(file, out, 'utf-8');
}

// Keeps the previous timestamp when nothing else changed, so the hourly sync
// only commits real changes.
function writeStamped(file, value, stampKey, serialize) {
  if (fs.existsSync(file)) {
    try {
      const previous = JSON.parse(fs.readFileSync(file, 'utf-8'));
      const same = serialize({ ...previous, [stampKey]: null }) === serialize({ ...value, [stampKey]: null });
      if (same) return false;
    } catch {}
  }
  fs.writeFileSync(file, serialize(value), 'utf-8');
  return true;
}

function writeSite(families, modelsById, providers, relatedBySlug) {
  const removed = writePages(families, modelsById, providers, relatedBySlug);
  // The site-wide lists need every page, which a --pages preview doesn't render.
  if (!PAGE_FILTER) {
    updateDocsNavigation(families, removed);
    updateLlmsIndex(families);
  }
  return removed.length;
}

const LLMS_START = '<!-- GENERATED:MODEL-PAGES:START by scripts/build-model-catalog.js. Edit the generator, not this block. -->';
const LLMS_END = '<!-- GENERATED:MODEL-PAGES:END -->';

// Lists every model page in llms.txt, between markers, at the end of the
// file on the first run; the rest of the file is hand-written.
function updateLlmsIndex(families) {
  const file = path.join(ROOT, 'llms.txt');
  const raw = fs.readFileSync(file, 'utf-8');
  const pages = [...families].sort((a, b) => a.name.localeCompare(b.name, 'en') || a.slug.localeCompare(b.slug))
    .map(f => `- [${seoTitle(f).replace(/[[\]]/g, '\\$&')}](https://docs.venice.ai/models/${f.slug})`);
  const block = [LLMS_START, '## Model pages', '', 'One page per model family, with pricing, specs, variants and a request example.', '', ...pages, LLMS_END].join('\n');
  const start = raw.indexOf(LLMS_START);
  const end = raw.indexOf(LLMS_END);
  const out = start >= 0 && end > start
    ? raw.slice(0, start) + block + raw.slice(end + LLMS_END.length)
    : `${raw.replace(/\s*$/, '')}\n\n${block}\n`;
  if (out !== raw) fs.writeFileSync(file, out, 'utf-8');
}

// A page's inline data: the family and the full records of its variants.
function readPageData(slug) {
  const file = path.join(MODELS_DIR, `${slug}.mdx`);
  if (!fs.existsSync(file)) return null;
  const match = fs.readFileSync(file, 'utf-8').match(/^<HubMount view="ModelPage" data=\{(.*)\} \/>$/m);
  return match ? JSON.parse(match[1]) : null;
}

// Re-renders pages and the nav group from committed data, for changes to
// rendering only. The catalog lists the families; descriptions, sources and
// voices aren't in it, so each family's full record is read back from its
// page, which the last online build wrote from the same snapshot. Endpoints
// are derived again, since pages written before `supported: false` was kept
// lack it.
async function renderOffline() {
  const catalog = readJson('model-catalog.json', null);
  if (!catalog) throw new Error('--offline needs data/model-catalog.json');
  const overrides = readJson('model-overrides.json', {});
  const modelsById = {};
  const families = catalog.families.map(entry => {
    const page = readPageData(entry.slug);
    if (!page) throw new Error(`--offline needs models/${entry.slug}.mdx; run the online build instead`);
    page.models.forEach(model => {
      model.endpoints = endpointsFor(model, overrides);
      modelsById[model.id] = model;
    });
    return page.family;
  });
  const relatedBySlug = Object.fromEntries(families.map(f => [f.slug, relatedFor(f, families, modelsById)]));
  const removed = writeSite(families, modelsById, catalog.providers, relatedBySlug);
  console.log(`Rendered ${PAGE_FILTER ? PAGE_FILTER.size : families.length} family pages from data/model-catalog.json`);
  if (removed) console.log(`Removed ${removed} stale family pages`);
}

// ---------------------------------------------------------------- main

async function main() {
  const ctx = {
    videoPricing: readJson('video-pricing.json', { models: {} }),
    overrides: readJson('model-overrides.json', {}),
    media: readJson('model-media.json', { models: {} }),
    renders: readJson('model-renders.json', { models: {} }),
    benchmarks: readJson('model-benchmarks.json', { results: {} }),
    telemetry: readJson('model-telemetry.json', { models: {} })
  };

  const raw = await loadModels();
  const models = raw.map(model => normalizeModel(model, ctx));
  const modelsById = Object.fromEntries(models.map(m => [m.id, m]));
  const families = buildFamilies(models);
  const familyByKey = Object.fromEntries(families.map(f => [f.key, f]));
  models.forEach(model => { model.family = familyByKey[model.familyKey].slug; });

  const providers = Object.fromEntries(PROVIDERS.map(([slug, name, logo]) => [slug, { slug, name, logo: `/images/icons/models/${logo}` }]));
  Object.entries(ctx.overrides.providers || {}).forEach(([slug, value]) => { providers[slug] = { slug, ...providers[slug], ...value }; });
  // Providers we could not identify fall back to the family name so no row renders blank.
  for (const family of families) {
    if (!family.provider) {
      const slug = slugify(family.name.split(/\s+/)[0]);
      family.provider = slug;
      family.variants.forEach(id => { modelsById[id].provider = slug; });
      if (!providers[slug]) providers[slug] = { slug, name: family.name.split(/\s+/)[0], logo: `/images/icons/models/${family.modality === 'video' ? 'video' : family.modality === 'image' ? 'image' : family.modality === 'audio' ? 'music' : 'text'}.svg`, inferred: true };
    }
  }

  families.sort((a, b) => (b.updated || 0) - (a.updated || 0) || a.name.localeCompare(b.name));
  const relatedBySlug = Object.fromEntries(families.map(f => [f.slug, relatedFor(f, families, modelsById)]));

  const usedProviders = new Set(families.map(f => f.provider));
  const counts = { models: models.length, families: families.length, byModality: {} };
  families.forEach(f => {
    const bucket = counts.byModality[f.modality] || (counts.byModality[f.modality] = { families: 0, models: 0 });
    bucket.families++;
    bucket.models += f.variants.length;
  });

  const catalog = {
    version: 1,
    generatedAt: new Date().toISOString(),
    counts,
    providers: Object.fromEntries(Object.entries(providers).filter(([slug]) => usedProviders.has(slug))),
    families: families.map(catalogFamily),
    models: Object.fromEntries(models.map(m => [m.id, catalogModel(m)])),
    benchmarks: ctx.benchmarks.benchmarks || null,
    mediaSuite: ctx.media.suite || null
  };

  const committed = readJson('model-catalog.json', null);
  checkSnapshotDrop('Catalog model count', committed && committed.counts && committed.counts.models, models.length);
  writeStamped(path.join(DATA, 'model-catalog.json'), catalog, 'generatedAt', value => JSON.stringify(value));
  const removed = writeSite(families, modelsById, providers, relatedBySlug);

  console.log(`Catalog: ${models.length} models in ${families.length} families`);
  Object.entries(counts.byModality).forEach(([modality, c]) => console.log(`  ${modality}: ${c.families} families / ${c.models} models`));
  if (removed) console.log(`Removed ${removed} stale family pages`);
}

(args.offline ? renderOffline : main)().catch(error => {
  console.error(error);
  process.exit(1);
});
