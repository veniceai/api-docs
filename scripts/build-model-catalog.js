function buildFamilies(models) {
  const groups = new Map();
  for (const model of models) {
    if (!groups.has(model.familyKey)) groups.set(model.familyKey, []);
    groups.get(model.familyKey).push(model);
  }

  const families = [];
  for (const [key, variants] of groups) {
    variants.sort((a, b) => VARIANT_ORDER.indexOf(a.variant) - VARIANT_ORDER.indexOf(b.variant) || (a.created || 0) - (b.created || 0));
    const primary = variants.find(v => ['standard', 'generate', 't2v'].includes(v.variant)) || variants[0];
    const modality = primary.modality;
    families.push({
      key,
      slug: slugify(primary.familyName),
      name: primary.familyName,
      modality,
      task: primary.task,
      provider: primary.provider,
      description: primary.description || variants.find(v => v.description)?.description || null,
      primary: primary.id,
      variants: variants.map(v => v.id),
      created: Math.min(...variants.map(v => v.created || Infinity)),
      updated: Math.max(...variants.map(v => v.created || 0)),
      privacy: [...new Set(variants.map(v => v.privacy))],
      uncensored: variants.some(v => v.uncensored),
      beta: variants.every(v => v.beta),
      deprecated: variants.every(v => v.deprecation),
      openWeights: variants.some(v => v.openWeights === true),
      traits: [...new Set(variants.flatMap(v => v.traits))],
      sets: [...new Set(variants.flatMap(v => v.sets))],
      modes: modality === 'video' ? variants.map(v => v.variant) : undefined
    });
  }

  // Resolve slug collisions (e.g. "Wan 2.7" exists as an image and a video family).
  const bySlug = new Map();
  families.forEach(family => {
    if (!bySlug.has(family.slug)) bySlug.set(family.slug, []);
    bySlug.get(family.slug).push(family);
  });
  for (const [slug, list] of bySlug) {
    if (list.length > 1) list.forEach(family => { family.slug = `${slug}-${family.modality}`; });
    list.forEach(family => { if (RESERVED_SLUGS.has(family.slug)) family.slug = `${family.slug}-model`; });
  }
  families.forEach(family => { if (!Number.isFinite(family.created)) family.created = null; });
  return families;
}

function lineageKey(family) {
  return `${family.modality}:${family.provider}:` + family.name.toLowerCase().replace(/[\d.]+/g, '').replace(/\s+/g, ' ').trim();
}

function relatedFor(family, families, modelsById) {
  const primary = modelsById[family.primary];
  const price = primary.headline?.value;
  const sameTask = families.filter(f => f !== family && f.modality === family.modality && f.task === family.task && !f.deprecated);
  const similar = sameTask
    .map(f => {
      const other = modelsById[f.primary];
      const otherPrice = other.headline?.value;
      const priceGap = price && otherPrice ? Math.abs(Math.log(otherPrice / price)) : 3;
      const recency = Math.abs((f.created || 0) - (family.created || 0)) / (86400 * 365);
      return { slug: f.slug, score: priceGap + recency * 0.5 + (f.provider === family.provider ? 0.4 : 0) };
    })
    .sort((a, b) => a.score - b.score)
    .slice(0, 4)
    .map(item => item.slug);
  const lineage = lineageKey(family);
  const versions = families
    .filter(f => f !== family && lineageKey(f) === lineage)
    .sort((a, b) => (b.created || 0) - (a.created || 0))
    .slice(0, 6)
    .map(f => f.slug);
  return { similar, versions };
}

