#!/usr/bin/env node
/**
 * Build the model hub from GET /models.
 *
 * Outputs:
 *   data/model-catalog.json   normalized models + families for the explorer
 *   models/<family>.mdx       one generated page per model family (hidden, searchable)
 *   docs.json                 the hidden "Models" group in the English Models tab, and
 *                             redirects for the pages of families that were removed
 *   llms.txt                  the "Model pages" block listing every page
 *
 * Optional inputs merged when present:
 *   data/video-pricing.json   quote matrix from scripts/quote-video-pricing.js
 *   data/model-overrides.json curated metadata the API does not expose yet
 *   data/model-media.json     reference outputs for image and video models
 *   data/model-renders.json   the docs' own renders, for models venice.ai has none for
 *   data/model-benchmarks.json, data/model-telemetry.json   future data feeds
 *
 * Refuses to overwrite the catalog if the model count drops by more than 20%
 * against the committed one; --allow-drop accepts a real drop.
 *
 * Usage: node scripts/build-model-catalog.js [--input=<dir with <type>.json files>] [--allow-drop]
 *                                            [--pages=<slug,...>]  generate only these pages (local preview)
 *                                            [--offline]  re-render pages from the committed data, no fetch
 */

